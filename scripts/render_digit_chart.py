#!/usr/bin/env python3
"""Render docs/digit-chart.svg, docs/example-1986.svg and the website favicon from the reference encoder.

A review aid: draws every digit motif in every quadrant plus a set of
composite examples. Standard library only; output is byte-for-byte
deterministic.

Usage:
    python3 scripts/render_digit_chart.py            # write the SVGs
    python3 scripts/render_digit_chart.py --check    # fail if any SVG is stale
    python3 scripts/render_digit_chart.py --edges N  # print canonical edges of N
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from judge.geometry import format_edges, normalize  # noqa: E402
from judge.reference import GRID_MAX_X as WIDTH, GRID_MAX_Y as HEIGHT, PLACES, STEM, encode_segments, motif  # noqa: E402


# ---------------------------------------------------------------- SVG output

UNIT = 22          # pixels per grid unit
CELL_W, CELL_H = 86, 118
PAD_X, PAD_Y = 24, 20
COMPOSITES = (1, 1986, 1993, 4723, 6859, 7085, 9433, 1992, 8971, 9938, 9999, 1001, 1010, 202)


def fmt(v: float) -> str:
    return f"{v:g}"


def draw_glyph(ox: float, oy: float, segments, stem_color: str | None, label: str) -> list[str]:
    gx = ox + (CELL_W - WIDTH * UNIT) / 2
    gy = oy + 12
    out = [f'<g><title>{label}</title>']
    for x in range(WIDTH + 1):
        for y in range(HEIGHT + 1):
            out.append(f'<circle cx="{fmt(gx + x * UNIT)}" cy="{fmt(gy + y * UNIT)}" r="1.6" fill="#b8b8b8"/>')

    def line(seg, color, width):
        (x1, y1), (x2, y2) = seg
        return (f'<line x1="{fmt(gx + x1 * UNIT)}" y1="{fmt(gy + y1 * UNIT)}" '
                f'x2="{fmt(gx + x2 * UNIT)}" y2="{fmt(gy + y2 * UNIT)}" '
                f'stroke="{color}" stroke-width="{width}" stroke-linecap="round"/>')

    if stem_color:
        out.append(line(STEM, stem_color, 3))
    for seg in segments:
        out.append(line(seg, "#111", 3.5))
    out.append(f'<text x="{fmt(ox + CELL_W / 2)}" y="{fmt(gy + HEIGHT * UNIT + 24)}" '
               f'text-anchor="middle">{label}</text>')
    out.append("</g>")
    return out


def render_svg() -> str:
    cols = 9
    comp_rows = -(-len(COMPOSITES) // (cols + 1))  # composites use the label column too
    width = PAD_X * 2 + 110 + cols * CELL_W
    motif_top = PAD_Y + 46
    comp_top = motif_top + 4 * CELL_H + 52
    height = comp_top + comp_rows * CELL_H + 40

    out = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" font-family="Helvetica, Arial, sans-serif" font-size="13" fill="#111">',
        "<!-- Generated by scripts/render_digit_chart.py from judge/reference.py. Do not edit by hand. -->",
        f'<rect width="{width}" height="{height}" fill="#fff"/>',
        f'<text x="{PAD_X}" y="{PAD_Y + 14}" font-size="18" font-weight="bold">'
        "Cistercian digit chart (contract v1)</text>",
        f'<text x="{PAD_X}" y="{PAD_Y + 34}" fill="#555">Grid x 0..2, y 0..3, origin top-left. '
        "Grey: mandatory stem. Black: digit motif. Dots: grid points.</text>",
    ]
    for place, name in enumerate(PLACES):
        oy = motif_top + place * CELL_H
        out.append(f'<text x="{PAD_X}" y="{fmt(oy + 12 + 1.5 * UNIT)}" font-weight="bold">{name}</text>')
        for digit in range(1, 10):
            ox = PAD_X + 110 + (digit - 1) * CELL_W
            out += draw_glyph(ox, oy, motif(digit, place), "#c4c4c4", str(digit * 10**place))

    out.append(f'<text x="{PAD_X}" y="{comp_top - 14}" font-size="15" font-weight="bold">'
               "Composite examples (full glyph)</text>")
    for i, n in enumerate(COMPOSITES):
        row, col = divmod(i, cols + 1)
        out += draw_glyph(PAD_X + col * CELL_W, comp_top + row * CELL_H, encode_segments(n), None, str(n))
    out.append("</svg>")
    return "\n".join(out) + "\n"


def render_example(n: int) -> str:
    """A small standalone glyph for the README."""
    unit, margin = 40, 16
    width, height = WIDTH * unit + 2 * margin, HEIGHT * unit + 2 * margin
    lines = "\n".join(
        f'  <line x1="{margin + x1 * unit}" y1="{margin + y1 * unit}" x2="{margin + x2 * unit}" y2="{margin + y2 * unit}"/>'
        for (x1, y1), (x2, y2) in encode_segments(n)
    )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" '
        f'role="img" aria-label="Cistercian numeral for {n}">\n'
        f"<!-- Generated by scripts/render_digit_chart.py from judge/reference.py. Do not edit by hand. -->\n"
        f"<title>Cistercian numeral for {n}</title>\n"
        f'<rect width="{width}" height="{height}" fill="#fff"/>\n'
        f'<g stroke="#111" stroke-width="5" stroke-linecap="round">\n{lines}\n</g>\n</svg>\n'
    )


def render_favicon(n: int = 1986) -> str:
    """Website favicon: light strokes on a rounded accent square (legible on light and dark tabs)."""
    size, unit, stroke = 64, 14, 6
    ox, oy = (size - WIDTH * unit) / 2, (size - HEIGHT * unit) / 2
    lines = "".join(
        f'<line x1="{fmt(ox + x1 * unit)}" y1="{fmt(oy + y1 * unit)}" x2="{fmt(ox + x2 * unit)}" y2="{fmt(oy + y2 * unit)}"/>'
        for (x1, y1), (x2, y2) in encode_segments(n)
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}">'
        f"<!-- Cistercian numeral {n}. Generated by scripts/render_digit_chart.py. Do not edit by hand. -->"
        f'<rect width="{size}" height="{size}" rx="14" fill="#8a3a26"/>'
        f'<g stroke="#fbfaf7" stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{lines}</g>'
        "</svg>\n"
    )


def outputs() -> dict[Path, str]:
    """Every generated file and its expected content."""
    return {
        ROOT / "docs" / "digit-chart.svg": render_svg(),
        ROOT / "docs" / "example-1986.svg": render_example(1986),
        ROOT / "web" / "public" / "favicon.svg": render_favicon(1986),
    }


def main(argv: list[str]) -> int:
    if argv[:1] == ["--edges"]:
        from judge.reference import encode
        for arg in argv[1:]:
            print(arg, format_edges(normalize(encode(int(arg)))))
        return 0
    stale = [path for path, svg in outputs().items()
             if not path.exists() or path.read_text(encoding="utf-8") != svg]
    if argv[:1] == ["--check"]:
        for path in stale:
            print(f"{path} is missing or stale; rerun without --check", file=sys.stderr)
        if not stale:
            print("generated SVGs are up to date")
        return 1 if stale else 0
    for path, svg in outputs().items():
        path.write_text(svg, encoding="utf-8")
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
